"""
LECO complaint cleaning - step 1

Reads   leco_null_removed.xlsx          (columns: Category, Description)
Writes  after_step1_leco_clean_kept.xlsx
        after_step1_leco_clean_removed.xlsx

Rows are removed when:
  1. it is a mobile-app template row with no "*Comment:" part
     (or the Comment part is there but empty)
  2. the text is mostly question marks
  3. the row is only a reference code, e.g. OTDL26081702 or
     OT/DL/26/07/20/08

Run:
    pip install pandas openpyxl
    python leco_clean_step1.py
"""

import re
from pathlib import Path

import pandas as pd

FOLDER = Path(r"D:\SLIIT\Y4S1\Research\data_cleaning\leco")
INPUT_FILE = FOLDER / "leco_null_removed.xlsx"
KEPT_FILE = FOLDER / "after_step1_leco_clean_kept.xlsx"
REMOVED_FILE = FOLDER / "after_step1_leco_clean_removed.xlsx"
TEXT_COL = "Description"

# A text is "mostly question marks" if at least this share of its characters is "?".
QUESTION_MARK_RATIO = 0.5

# False: remove a row only when the code is the whole description.
# True : remove a row when a code appears anywhere in it (also drops real
#        complaints, such as emails, that merely quote a reference code).
REMOVE_IF_CODE_ANYWHERE = False

# "*Comment:*", "*Comment:", "Comment:*" ...
COMMENT_RE = re.compile(r"Comment\s*:", re.IGNORECASE)

# Letters, then digits, optionally split by "/" or "-":
#   OTDL26081702      OT/DL/26/07/20/08
CODE = r"[A-Za-z]{2,6}(?:[/-][A-Za-z]{1,6})*[/-]?\d{2,}(?:[/-]\d+)*"
CODE_ONLY_RE = re.compile(rf"^(?:{CODE})$")
CODE_ANYWHERE_RE = re.compile(rf"(?<![A-Za-z0-9]){CODE}(?![A-Za-z0-9])")


def is_template(text: str) -> bool:
    """True for messages generated by the mobile-app template."""
    t = text.lower()
    return "mobile number" in t and "complaint category" in t


def is_mostly_question_marks(text: str) -> bool:
    chars = re.sub(r"\s", "", text)
    if not chars:
        return False
    return chars.count("?") / len(chars) >= QUESTION_MARK_RATIO


def is_reference_code(text: str) -> bool:
    if REMOVE_IF_CODE_ANYWHERE:
        return bool(CODE_ANYWHERE_RE.search(text))
    tokens = [t for t in re.split(r"[\s,;]+", text.strip()) if t]
    return bool(tokens) and all(CODE_ONLY_RE.match(t) for t in tokens)


def should_remove(text: str) -> bool:
    """True if the row should be removed."""
    body = text
    if is_template(text):
        m = COMMENT_RE.search(text)
        if not m:
            return True                             # template row, no Comment part
        body = text[m.end():].strip(" *\n\r\t")    # the text after "Comment:"
        if body == "":
            return True                             # Comment part is empty
    return is_mostly_question_marks(body) or is_reference_code(body)


def main() -> None:
    df = pd.read_excel(INPUT_FILE)
    remove = df[TEXT_COL].fillna("").astype(str).apply(should_remove)

    kept = df[~remove]
    removed = df[remove]

    kept.to_excel(KEPT_FILE, index=False)
    removed.to_excel(REMOVED_FILE, index=False)

    print(f"Input rows : {len(df)}")
    print(f"Kept       : {len(kept)}")
    print(f"Removed    : {len(removed)}")


if __name__ == "__main__":
    main()