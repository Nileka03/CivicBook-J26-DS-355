"""
LECO complaint cleaning - step 3

For mobile-app template rows, keep only the text after "Comment:".
All other rows are left exactly as they are.

Reads   after_step2_leco_clean_kept.xlsx   (columns: Category, Description)
Writes  after_step3_leco_clean.xlsx

Run:
    python leco_clean_step3.py
"""

import re
import unicodedata
from pathlib import Path

import pandas as pd

FOLDER = Path(r"D:\SLIIT\Y4S1\Research\data_cleaning\leco")
INPUT_FILE = FOLDER / "after_step2_leco_clean_kept.xlsx"
OUTPUT_FILE = FOLDER / "after_step3_leco_clean.xlsx"
TEXT_COL = "Description"

# "*Comment:*", "*Comment:", "Comment:*" ...
COMMENT_RE = re.compile(r"Comment\s*:", re.IGNORECASE)


def is_template(text: str) -> bool:
    """True for messages generated by the mobile-app template."""
    t = text.lower()
    return "mobile number" in t and "complaint category" in t


def is_junk(ch: str) -> bool:
    """Spaces, '*', and invisible/control characters."""
    return ch == "*" or unicodedata.category(ch)[0] in "CZ"


def trim(text: str) -> str:
    """Remove junk characters from the start and the end only.
    The inside of the text is not touched."""
    start, end = 0, len(text)
    while start < end and is_junk(text[start]):
        start += 1
    while end > start and is_junk(text[end - 1]):
        end -= 1
    return text[start:end]


def keep_comment(text):
    """Return only the comment for template rows; other rows unchanged."""
    if not isinstance(text, str) or not is_template(text):
        return text
    m = COMMENT_RE.search(text)
    if not m:
        return text                 # no Comment part: leave the row as it is
    return trim(text[m.end():])


def main() -> None:
    df = pd.read_excel(INPUT_FILE)
    before = df[TEXT_COL]
    df[TEXT_COL] = before.apply(keep_comment)

    changed = (before.fillna("") != df[TEXT_COL].fillna("")).sum()
    still_template = df[TEXT_COL].fillna("").astype(str).apply(is_template).sum()
    empty = (df[TEXT_COL].fillna("").astype(str).str.strip() == "").sum()

    df.to_excel(OUTPUT_FILE, index=False)

    print(f"Rows                       : {len(df)}")
    print(f"Changed to comment only    : {changed}")
    print(f"Template rows left as-is   : {still_template}   (no Comment part)")
    print(f"Rows with empty description: {empty}")
    print(f"\nWritten to {OUTPUT_FILE.name}")


if __name__ == "__main__":
    main()